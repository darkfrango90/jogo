const normalize = (value: string) =>
  value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();
export const WORDS: WordEntry[] = Object.entries(categories).flatMap(
  ([category, words]) =>
    words.map((word, index) => ({
      id: `${normalize(category).replace(/[^a-z]+/g, "-")}-${String(index + 1).padStart(2, "0")}`,
      word,
      category,
      difficulty: index < 25 ? "média" : "difícil",
      hint: `Termo de ${category.toLowerCase()} com ${[...word].filter((c) => /[A-Za-zÀ-ÿ]/.test(c)).length} letras.`,
    })),
);

export function validateDictionary() {
  if (WORDS.length !== 500)
    throw new Error(`Dicionário inválido: ${WORDS.length} palavras`);
  const unique = new Set(
    WORDS.map((x) => normalize(x.word).replace(/[^a-z]/g, "")),
  );
  if (unique.size !== 500)
    throw new Error("Dicionário contém palavras duplicadas");
  for (const [category, words] of Object.entries(categories)) {
    if (words.length !== 50)
      throw new Error(`${category} deve conter 50 palavras`);
    const entries = WORDS.filter((x) => x.category === category);
    if (
      entries.filter((x) => x.difficulty === "média").length !== 25 ||
      entries.filter((x) => x.difficulty === "difícil").length !== 25
    )
      throw new Error(`Distribuição inválida em ${category}`);
    if (entries.some((x) => !x.hint || !x.id))
      throw new Error(`Metadados incompletos em ${category}`);
  }
  return true;
}
validateDictionary();
